HERE = os.path.dirname(os.path.abspath(__file__))
SK = os.path.join(HERE, "..", "..", "plugins", "records-skills", "skills")


def xlsx(path, rows, sheet=None):
    wb = openpyxl.Workbook()
    ws = wb.active
    if sheet:
        ws.title = sheet
    for r in rows:
        ws.append(r)
    wb.save(path)


def run(name, script, *args):
    d = os.path.join(HERE, name)
    cmd = [sys.executable, os.path.join(SK, *script.split("/"))] + [a.replace("{d}", d) for a in args]
    p = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8")
    print(f"[{name}] {p.stdout.strip() or p.stderr.strip()}")
    return p.returncode


def fresh(name):
    d = os.path.join(HERE, name)
    for sub in ("입력", "결과"):
        shutil.rmtree(os.path.join(d, sub), ignore_errors=True)
        os.makedirs(os.path.join(d, sub))
    return d


